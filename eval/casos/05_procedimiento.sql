CREATE TABLE dbo.TBL_PEDIDOS (
    ID_PEDIDO INT IDENTITY PRIMARY KEY,
    MONTO FLOAT NOT NULL,
    OBSERVACION TEXT NULL
);
GO
CREATE PROCEDURE dbo.sp_ListarPedidos
    @Filtro NVARCHAR(100)
AS
BEGIN
    DECLARE @sql NVARCHAR(MAX) = N'SELECT * FROM dbo.TBL_PEDIDOS WHERE OBSERVACION LIKE ''%' + @Filtro + '%''';
    EXEC(@sql);
    SELECT * FROM dbo.TBL_PEDIDOS WHERE YEAR(FECHA) = 2026;
END
